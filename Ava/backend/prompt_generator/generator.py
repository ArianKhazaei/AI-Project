def generate_prompt(user_prompt: str) -> str:
    """
    تبدیل ورودی خام به یک Final Prompt ساختاریافته.
    """

    if not isinstance(user_prompt, str):
        raise TypeError("Prompt باید از نوع متن باشد.")

    user_prompt = user_prompt.strip()

    if not user_prompt:
        raise ValueError("Prompt نمی‌تواند خالی باشد.")

    return f"""
تو یک دستیار هوش مصنوعی دقیق و حرفه‌ای هستی.

درخواست کاربر:
{user_prompt}

دستورالعمل:
- هدف اصلی کاربر را دقیق درک کن.
- مستقیماً به درخواست کاربر پاسخ بده.
- اطلاعاتی را که کاربر ارائه نکرده، بدون دلیل اضافه نکن.
- اگر درخواست مبهم است، منطقی‌ترین برداشت را بر اساس اطلاعات موجود انتخاب کن.
- پاسخ را واضح، ساختاریافته و متناسب با درخواست ارائه کن.
- از توضیحات غیرضروری خودداری کن.
""".strip()
